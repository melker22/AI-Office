# Self-test: drive the whole checker through main with a stub CLI.


STUB_CLI = """#!{python}
import json, os, sys
canned = json.load(open({canned!r}, encoding="utf-8"))
key = os.path.basename(sys.argv[2]) if len(sys.argv) > 2 else ""
print(json.dumps(canned.get(key, {{"ok": False, "error": "no canned response for " + key}})))
"""


def canned_document() -> dict[str, Any]:
    return {
        "meta": {"title": "t", "author": "a"},
        "body": [
            {"type": "paragraph", "runs": [{"text": "ok"}]},
            {"type": "image", "image_mime": "image/png", "image_b64": ""},
        ],
    }


def run_main(args: list[str]) -> int:
    argv = sys.argv
    sys.argv = [str(Path(__file__).name), *args]
    try:
        return main()
    finally:
        sys.argv = argv


def self_test(cli: Path) -> int:
    errors: list[str] = []
    workdir = Path(tempfile.mkdtemp(prefix="aio-wave27-selftest-"))
    try:
        canned_path = workdir / "canned.json"
        canned = {
            "wave27-broken.epub": {"ok": False, "error": "OEBPS/ch1.xhtml: Expected '>' at line 2"},
            "wave27-drm.epub": {"ok": False, "error": "EPUB is DRM-protected: OEBPS/ch1.xhtml"},
            "wave27-big-image.epub": {"ok": False, "error": "EPUB image exceeds 32MB: OEBPS/images/big.png"},
            "wave27-oversized.epub": {"ok": False, "error": "archive entry too large"},
            "wave27-hostile.epub": {
                "ok": True,
                "document": canned_document(),
                "warnings": ["EPUB import: ignored href ../secret.xhtml", "EPUB import: ignored href file:///etc/passwd"],
            },
        }
        canned_path.write_text(json.dumps(canned), encoding="utf-8")
        stub = workdir / "stub-cli"
        stub.write_text(STUB_CLI.format(python=sys.executable, canned=str(canned_path)), encoding="utf-8")
        stub.chmod(0o755)

        rc = run_main(["--check", "d7", "--cli", str(stub)])
        if rc != 0:
            errors.append(f"self-test: a matching stub CLI did not pass d7 (rc={rc})")
        canned["wave27-broken.epub"] = {"ok": False, "error": "opened fine"}
        canned_path.write_text(json.dumps(canned), encoding="utf-8")
        rc = run_main(["--check", "d7", "--cli", str(stub)])
        if rc == 0:
            errors.append("self-test: a wrong error message still passed d7")

        # The real CLI path must be accepted by the checker (no fixed build dir).
        if not cli.is_file():
            errors.append(f"self-test: ctest passed a CLI that does not exist: {cli}")
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    if errors:
        for err in errors:
            print(f"FAIL {err}")
        return 1
    print("ok   wave27 epub self-test")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", type=Path, default=REPO / "build/linux/aioffice-cli")
    parser.add_argument("--check", choices=["d6", "d7", "all"], default="all")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    cli = args.cli.resolve()
    if args.self_test:
        return self_test(cli)
    if not cli.is_file():
        raise SystemExit(f"missing cli: {cli}")
    workdir = Path(tempfile.mkdtemp(prefix="aio-wave27-"))
    try:
        errors: list[str] = []
        if args.check in ("d6", "all"):
            errors.extend(check_d6(cli, workdir))
        if args.check in ("d7", "all"):
            errors.extend(check_d7(cli, workdir))
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    if errors:
        for err in errors:
            print(f"FAIL {err}")
        return 1
    print(f"ok   wave27 epub import ({args.check})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())