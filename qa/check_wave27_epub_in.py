def spawn_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = dict(os.environ)
    env.pop("LD_PRELOAD", None)
    env["AIOFFICE_HEADLESS"] = "1"
    env["QT_QPA_PLATFORM"] = "offscreen"
    if extra:
        env.update(extra)
    return env


def run_cli(cli: Path, argv: list[str], *, extra_env: dict[str, str] | None = None) -> Any:
    try:
        proc = subprocess.run(
            [str(cli), *argv],
            capture_output=True,
            text=True,
            timeout=CLI_TIMEOUT,
            cwd=REPO,
            env=spawn_env(extra_env),
            check=False,
        )
    except FileNotFoundError as exc:
        raise SystemExit(f"missing CLI: {cli}") from exc
    except subprocess.TimeoutExpired as exc:
        raise SystemExit(f"timeout after {CLI_TIMEOUT}s: {' '.join(argv)}") from exc
    raw = proc.stdout.strip()
    if not raw:
        raise SystemExit(f"{' '.join(argv)} produced no output (rc={proc.returncode}): {proc.stderr.strip()[:300]}")
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{' '.join(argv)} produced bad JSON: {exc}: {raw[:300]}") from exc


def open_book(cli: Path, path: Path, *, extra_env: dict[str, str] | None = None) -> dict[str, Any]:
    return run_cli(cli, ["open", str(path)], extra_env=extra_env)


def play(cli: Path, playbook: Path) -> dict[str, Any]:
    return run_cli(cli, ["play", str(playbook)])


