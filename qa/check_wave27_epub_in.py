def check_d7(cli: Path, workdir: Path) -> list[str]:
    errors: list[str] = []

    broken = workdir / "wave27-broken.epub"
    write_broken_xml_epub(broken)
    out = open_book(cli, broken)
    if out.get("ok"):
        fail(errors, "malformed XHTML opened successfully")
    else:
        err = str(out.get("error", ""))
        if not re.search(r"ch1\.xhtml: .+ at line \d+$", err):
            fail(errors, f"malformed XHTML message is not '<file>: <error> at line N': {err!r}")

    drm = workdir / "wave27-drm.epub"
    write_drm_epub(drm)
    out = open_book(cli, drm)
    if out.get("ok"):
        fail(errors, "DRM EPUB opened successfully")
    elif "DRM" not in str(out.get("error", "")):
        fail(errors, f"DRM error is not clear: {out.get('error')!r}")

    big = workdir / "wave27-big-image.epub"
    write_big_image_epub(big)
    out = open_book(cli, big)
    if out.get("ok"):
        fail(errors, "an image above 32 MiB was accepted")
    elif "32MB" not in str(out.get("error", "")):
        fail(errors, f"oversized image error is not clear: {out.get('error')!r}")

    oversized = workdir / "wave27-oversized.epub"
    write_oversized_entry_epub(oversized)
    out = open_book(cli, oversized, extra_env={"AIOFFICE_ZIP_ENTRY_CAP": "200000"})
    if out.get("ok"):
        fail(errors, "an archive entry above the wave23 cap was accepted")
    elif "archive entry too large" not in str(out.get("error", "")):
        fail(errors, f"zip entry cap error is not clear: {out.get('error')!r}")

    # Hostile hrefs: no network request may leave the process, and the two
    # ignored hrefs/images must be reported. The HTTP server counts requests.
    hits: list[str] = []

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self) -> None:  # noqa: N802 (stdlib name)
            hits.append(self.path)
            self.send_response(200)
            self.send_header("Content-Type", "image/png")
            self.end_headers()
            self.wfile.write(PNG_1X1)

        def log_message(self, *args: Any) -> None:
            return

    server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
    port = server.server_address[1]
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        foreign = workdir / "wave27-hostile.epub"
        write_third_party_epub(foreign, port)
        out = open_book(cli, foreign)
        if not out.get("ok"):
            fail(errors, f"hostile-href book did not open: {out.get('error')}")
        else:
            warnings = out.get("warnings", [])
            joined = " | ".join(warnings) if isinstance(warnings, list) else ""
            if not joined:
                fail(errors, "no warning for the hostile hrefs")
            images = [b for b in out.get("document", {}).get("body", []) if b.get("type") == "image"]
            if len(images) != 1:
                fail(errors, f"a network image became a block: {len(images)} images")
        thread.join(timeout=0.2)
        if hits:
            fail(errors, f"the reader fetched over the network: {hits}")
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
    return errors


