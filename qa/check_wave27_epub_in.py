#!/usr/bin/env python3
"""Wave 27 EPUB import judges (D6, D7, and the EPUB half of D2).

Every fixture is generated by this script in a private temp directory (no opaque
binary is committed): an EPUB exported by our own writer (through a generated
playbook) and hand-written third-party/hostile EPUBs. The judges open them with
the real CLI and check the block tree, the note paragraphs, and the error and
warning paths.

* ``--check d6``  block mapping (headings, paragraphs, runs, lists, tables,
  images, captions, notes with U+2029, language, direction, styles, internal
  links, metadata) and the EPUB exported by us.
* ``--check d7``  hostile input: malformed XML message, DRM, zip/entry and image
  limits, discarded containers, ignored hrefs, and no network access.

The CLI path comes from ctest; the self-test runs the whole check pipeline
through ``main`` against a stub CLI, so this script's own wiring can fail.
"""

