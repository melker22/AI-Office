def block_text(block: dict[str, Any]) -> str:
    return "".join(run.get("text", "") for run in block.get("runs", []))


def all_text(blocks: list[dict[str, Any]]) -> str:
    out: list[str] = []

    def walk(block: dict[str, Any]) -> None:
        out.append(block_text(block))
        for row in block.get("rows", []):
            for cell in row:
                for run in cell.get("runs", []):
                    out.append(run.get("text", ""))
                for nrow in cell.get("nested", []):
                    for ncell in nrow:
                        for run in ncell.get("runs", []):
                            out.append(run.get("text", ""))
        for run in block.get("caption_runs", []):
            out.append(run.get("text", ""))
        out.append(block.get("caption", ""))

    for b in blocks:
        walk(b)
    return "\n".join(out)


def find_block(blocks: list[dict[str, Any]], *, type_: str | None = None, text: str | None = None,
               level: int | None = None) -> dict[str, Any] | None:
    for b in blocks:
        if type_ and b.get("type") != type_:
            continue
        if level is not None and b.get("level") != level:
            continue
        if text is not None and block_text(b) != text:
            continue
        return b
    return None


def find_run(block: dict[str, Any], text: str) -> dict[str, Any] | None:
    for run in block.get("runs", []):
        if run.get("text") == text:
            return run
    return None


def fail(errors: list[str], message: str) -> None:
    errors.append(message)


