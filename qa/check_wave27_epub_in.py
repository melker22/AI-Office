def check_foreign_book(doc: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    meta = doc.get("meta", {})
    if meta.get("title") != "Terceiro Livro":
        fail(errors, f"metadata title is {meta.get('title')!r}")
    if meta.get("author") != "Autora Estranha":
        fail(errors, f"metadata author is {meta.get('author')!r}")
    blocks = doc.get("body", [])
    if not blocks:
        return ["foreign EPUB imported no blocks"]

    h1 = find_block(blocks, type_="heading", text="Chapter One")
    if not h1 or h1.get("level") != 1:
        fail(errors, "h1 is not a level 1 heading")
    h2 = find_block(blocks, type_="heading", text="Section")
    if not h2 or h2.get("level") != 2:
        fail(errors, "h2 is not a level 2 heading")

    plain = find_block(blocks, type_="paragraph", text="Plain bold ital under strike sub2 sup3 ext")
    if not plain:
        fail(errors, f"formatted paragraph not found: {[block_text(b) for b in blocks][:8]}")
    else:
        for text, flag in (
            ("bold", "bold"),
            ("ital", "italic"),
            ("under", "underline"),
            ("strike", "strike"),
            ("2", "subscript"),
            ("3", "superscript"),
        ):
            run = find_run(plain, text)
            if not run or not run.get(flag):
                fail(errors, f"run {text!r} lacks {flag}")
        ext = find_run(plain, "ext")
        if not ext or ext.get("link") != "https://example.org/x":
            fail(errors, f"external link not kept: {ext}")

    span = find_block(blocks, type_="paragraph", text="spanfmt")
    if not span:
        fail(errors, "inline style span paragraph not found")
    else:
        run = find_run(span, "spanfmt")
        if not run or not (run.get("bold") and run.get("italic") and run.get("underline")):
            fail(errors, f"inline font-weight/font-style/text-decoration not applied: {run}")

    rtl = find_block(blocks, type_="paragraph", text="RTL text")
    if not rtl:
        fail(errors, "rtl paragraph not found")
    else:
        if rtl.get("lang") != "pt":
            fail(errors, f"xml:lang not stored on the block: {rtl.get('lang')!r}")
        if rtl.get("dir") != "rtl":
            fail(errors, f"dir not stored on the block: {rtl.get('dir')!r}")

    internal = find_block(blocks, type_="paragraph", text="Back to chapter")
    if not internal:
        fail(errors, "internal link paragraph not found")
    else:
        run = find_run(internal, "chapter")
        want = "#" + h1.get("id", "") if h1 else None
        if not run or run.get("link") != want:
            fail(errors, f"internal link not remapped to the imported block id: {run} != {want}")

    kinds = sorted(b.get("type") for b in blocks)
    if kinds.count("list-item") != 3:
        fail(errors, f"expected 3 list items, got {kinds.count('list-item')}: {[(block_text(b), b.get('level'), b.get('list_kind')) for b in blocks if b.get('type') == 'list-item']}")
    bullet = find_block(blocks, type_="list-item", text="Bullet one", level=1)
    if not bullet or bullet.get("list_kind") != "bullet":
        fail(errors, f"outer bullet list item wrong: {bullet}")
    child = find_block(blocks, type_="list-item", text="Numbered child", level=2)
    if not child or child.get("list_kind") != "decimal":
        fail(errors, f"nested decimal list item wrong: {child}")
    second = find_block(blocks, type_="list-item", text="Bullet two", level=1)
    if not second:
        fail(errors, "second outer bullet item missing")

    table = find_block(blocks, type_="table")
    if not table:
        fail(errors, "table block missing")
    else:
        rows = table.get("rows", [])
        if not table.get("header"):
            fail(errors, "first row of th was not marked as the header")
        if not rows or len(rows) < 3:
            fail(errors, f"table grid too small: {rows}")
        else:
            head = rows[0][0] if rows[0] else {}
            if "".join(r.get("text", "") for r in head.get("runs", [])) != "Head" or head.get("col_span") != 2:
                fail(errors, f"header cell colspan not imported: {head}")
            a_cell = rows[1][0] if rows[1] else {}
            if "".join(r.get("text", "") for r in a_cell.get("runs", [])) != "A" or a_cell.get("row_span") != 2:
                fail(errors, f"rowspan cell not imported: {a_cell}")
            if len(rows[2]) < 2 or "".join(r.get("text", "") for r in rows[2][1].get("runs", [])) != "C":
                fail(errors, f"cell C not in column 1 of the third row: {rows[2]}")

    figure = [b for b in blocks if b.get("type") == "image"]
    if len(figure) != 1:
        fail(errors, f"expected exactly one image block (the network image must be ignored), got {len(figure)}")
    else:
        image = figure[0]
        if base64.b64decode(image.get("image_b64", "")) != PNG_1X1:
            fail(errors, "image bytes are not the package bytes")
        if image.get("image_mime") != "image/png":
            fail(errors, f"image media type is {image.get('image_mime')!r}")
        if image.get("alt") != "Pixel":
            fail(errors, f"image alt is {image.get('alt')!r}")
        if image.get("caption") != "Caption text":
            fail(errors, f"figcaption is not the block caption: {image.get('caption')!r}")

    notes = [b for b in blocks if b.get("type") == "footnote"]
    if len(notes) != 1:
        fail(errors, f"expected one footnote block, got {len(notes)}")
    else:
        note = notes[0]
        parts = block_text(note).split(PARAGRAPH_SEPARATOR)
        if parts != ["First note paragraph", "Second bold paragraph", "Third italic paragraph"]:
            fail(errors, f"note paragraphs are not U+2029 separated: {parts!r}")
        bold = find_run(note, "bold")
        if not bold or not bold.get("bold"):
            fail(errors, f"second note paragraph lost its bold: {note.get('runs')}")
        italic = find_run(note, "italic")
        if not italic or not italic.get("italic"):
            fail(errors, f"third note paragraph lost its italic: {note.get('runs')}")
        ref = None
        ref_para = find_block(blocks, type_="paragraph", text="Note1")
        if ref_para:
            ref = find_run(ref_para, "1")
        if not ref or ref.get("note_id") != note.get("id"):
            fail(errors, f"noteref does not point at the imported note: {ref} vs {note.get('id')}")
        cross = find_block(blocks, type_="paragraph", text="Cross2")
        cross_ref = find_run(cross, "2") if cross else None
        if not cross_ref or cross_ref.get("note_id") != note.get("id"):
            fail(errors, f"a note reference from another spine document was not resolved: {cross_ref}")

    text = all_text(blocks)
    for marker in ("NAV-ONLY", "SCRIPT-TEXT", "IFRAME-TEXT", "OBJECT-TEXT", "FORM-TEXT", "FORM-P"):
        if marker in text:
            fail(errors, f"discarded content leaked into the document: {marker}")
    return errors


