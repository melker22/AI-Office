def build_epub(
    path: Path,
    *,
    metadata: list[tuple[str, str]],
    manifest: list[dict[str, str]],
    spine: list[tuple[str, str]],
    files: dict[str, bytes],
    encryption: bytes | None = None,
    mimetype: bytes = b"application/epub+zip",
) -> None:
    opf = ['<?xml version="1.0" encoding="UTF-8"?>']
    opf.append(
        '<package xmlns="http://www.idpf.org/2007/opf" version="3.0" '
        'unique-identifier="pub-id">'
    )
    opf.append('<metadata xmlns:dc="http://purl.org/dc/elements/1.1/">')
    opf.append('<dc:identifier id="pub-id">urn:uuid:11111111-2222-3333-4444-555555555555</dc:identifier>')
    for tag, text in metadata:
        opf.append(f"<{tag}>{escape(text)}</{tag}>")
    opf.append("</metadata><manifest>")
    for item in manifest:
        props = f' properties={quoteattr(item["properties"])}' if item.get("properties") else ""
        opf.append(
            f'<item id={quoteattr(item["id"])} href={quoteattr(item["href"])} '
            f'media-type={quoteattr(item["media_type"])}{props}/>'
        )
    opf.append("</manifest><spine>")
    for idref, linear in spine:
        lin = f' linear={quoteattr(linear)}' if linear else ""
        opf.append(f'<itemref idref={quoteattr(idref)}{lin}/>')
    opf.append("</spine></package>")
    opf_bytes = "".join(opf).encode("utf-8")

    container = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">'
        "<rootfiles>"
        '<rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>'
        "</rootfiles></container>"
    ).encode("utf-8")

    with zipfile.ZipFile(path, "w") as zf:
        info = zipfile.ZipInfo("mimetype")
        info.compress_type = zipfile.ZIP_STORED
        zf.writestr(info, mimetype)
        zf.writestr("META-INF/container.xml", container, compress_type=zipfile.ZIP_DEFLATED)
        if encryption is not None:
            zf.writestr("META-INF/encryption.xml", encryption, compress_type=zipfile.ZIP_STORED)
        zf.writestr("OEBPS/content.opf", opf_bytes, compress_type=zipfile.ZIP_DEFLATED)
        for name, data in files.items():
            zf.writestr(name, data, compress_type=zipfile.ZIP_STORED if len(data) > 1 << 20 else zipfile.ZIP_DEFLATED)


def xhtml(body: str, *, lang: str = "en", extra_root: str = "") -> bytes:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<!DOCTYPE html>'
        f'<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"'
        f' xml:lang="{lang}" lang="{lang}"{extra_root}><head><title>t</title></head><body>'
        f"{body}</body></html>"
    ).encode("utf-8")


